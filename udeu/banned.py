# -*- coding: utf-8 -*-
"""Товары, которые Údeu не продаёт (решение владельца 12.10.2026).
Робот выкидывает их из всех фидов, а при сборе AGS они не попадают в фид."""
import re

RULES = [
    ('колёсные болты/шпильки/секретки',
     r'(болт|шпильк)\w*[^,.;]{0,25}колес|колес\w*[^,.;]{0,15}(болт|шпильк)|\bсекретк|шпильк\w* (для )?(колес|диск)'),
    ('ниппели и колпачки ниппелей', r'ниппел|колпач\w*[^,.;]{0,20}(вентил|ниппел)|вентил\w* (для )?(шин|колес|бескамер)'),
    ('зарядки (в салон и для АКБ)',
     r'(зарядн|пуско-?зарядн|беспроводн\w* заряд|заряд\w* устройств)(?![^,.;]{0,40}(электромобил|станци|кабел|порт|wallbox|type ?2|gb/t|ccs))'),
    ('манометры', r'манометр'),
    ('преобразователи напряжения', r'преобразовател\w* напряж|^инвертор'),
    ('держатели велосипедов и лыж', r'велосипед|велокрепл|\bлыж|сноуборд|\bbike\b|\bski\b'),
    ('сумки и чехлы для шин',
     r'\bсумк|\bсумоч|чехл\w* для (хранения )?(шин|колес|покрыш)|мешк\w* для (шин|колес)|\bкофр\w* для колес'),
    ('масла и автохимия',
     r'(моторн|трансмиссионн|синтетическ|полусинтетическ|минеральн)\w* масл|^масло\b|масло (для|в |atf|\d)|\d+w-?\d+|антифриз|омывающ|тормозн\w* жидкост|охлаждающ\w* жидкост|\bжидкост\w* (для|в) (омыв|стекл)|'
     r'\bсмазк|(?<!стекло)очистител|полирол|автошампун|\bшампун|присадк|автохими|\bгерметик|\bвоск|керамическ\w* покрыт|антидожд|'
     r'чернител|кондиционер для кож|нейтрализатор запах|ароматизатор|освежител'),
]
# не трогаем детали, у которых в названии только упоминается масло/зарядка/манометр
EXCEPT = {
    'масла и автохимия': r'шайб|радиатор|фильтр|щуп|крышк|пробк|насос|датчик|охладител|поддон|сальник|трубк|шланг|мотор стеклоочист|щет[оке]?к|переключател|форсунк',
    'зарядки (в салон и для АКБ)': r'коврик|наклейк|отделк|накладк|рамк|чехол для зарядн|спинк|столик|4xe|phev|электромобил|гибрид',
    'манометры': r'компрессор',
}
_EXC = {k: re.compile(v, re.I) for k, v in EXCEPT.items()}
_COMPILED = [(name, re.compile(rx, re.I)) for name, rx in RULES]


def banned(title):
    t = (title or '').lower().replace('ё', 'е')
    for name, rx in _COMPILED:
        if rx.search(t) and not (name in _EXC and _EXC[name].search(t)):
            return name
    return None
